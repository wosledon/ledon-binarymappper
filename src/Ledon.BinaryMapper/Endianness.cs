namespace Ledon.BinaryMapper;

/// <summary>
/// 表示二进制数据的字节序。<br/>
/// Represents the endianness of binary data.
/// </summary>
public enum Endianness
{
    /// <summary>
    /// 大端字节序。<br/>
    /// Big-endian byte order.
    /// </summary>
    BigEndian,

    /// <summary>
    /// 小端字节序。<br/>
    /// Little-endian byte order.
    /// </summary>
    LittleEndian
}
